const UNCERTAIN_BELOW = 0.7;

function isHealthy(label) {
  return /healthy/i.test(label);
}

function diseaseAdviceKey(label) {
  const value = label.toLowerCase();
  if (/spider.?mite/.test(value)) return "mite";
  if (/huanglongbing|citrus.?greening/.test(value)) return "urgent";
  if (/healthy/.test(value)) return "healthy";
  return "disease";
}

export function getLocalGuidance({ source, label, confidence, language }) {
  const copy = guidance[language];
  if (!copy) throw new Error("Choose a supported language before asking for crop guidance.");
  if (!["disease", "pest"].includes(source)) throw new Error("The guidance source is not supported.");
  if (!Number.isFinite(confidence) || confidence < 0 || confidence > 1) {
    throw new Error("The model confidence score is invalid.");
  }

  let action;
  if (confidence < UNCERTAIN_BELOW) {
    action = copy.lowConfidence;
  } else if (source === "disease" && confidence < 0.85) {
    action = copy.uncertain;
  } else if (source === "disease") {
    action = copy[diseaseAdviceKey(label)];
  } else if (source === "pest") {
    action = /predator|non.?pest/i.test(label) ? copy.beneficial : copy.pest;
  }

  return {
    category: source === "disease" && isHealthy(label) ? "healthy" : source,
    text: `${label} (${Math.round(confidence * 100)}% model score). ${action} ${copy.notice}`,
  };
}

export function localGuidanceThreshold() {
  return UNCERTAIN_BELOW;
}
